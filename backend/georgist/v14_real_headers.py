def read_header_fields(path: Path) -> list[str] | None:
    """Read the first header line and stop. Data rows are not read."""
    with path.open("r", encoding="utf-8", newline="") as handle:
        for line in handle:
            if not line.strip() or line.startswith("#"):
                continue
            return next(csv.reader([line]))
    return None


def header_refusal(
    step: str,
    name: str,
    header: list[str] | tuple[str, ...],
    *,
    legacy: tuple[str, ...] | None = None,
) -> str | None:
    """Return the refusal line when the header is not the real pinned header."""
    expected = REAL_HEADERS[name]
    actual = tuple(header)
    if actual == expected:
        return None
    if len(actual) == len(expected) + 1 and actual[:-1] == expected and actual[-1] == "price":
        return None
    if len(actual) > len(expected) and actual[: len(expected)] == expected:
        return None
    if legacy is not None and (
        actual == legacy or (len(actual) > len(legacy) and actual[: len(legacy)] == legacy)
    ):
        return None
    return (
        f"{step}: REFUSED: header: expected {','.join(expected)}, got {','.join(actual)}"
    )
